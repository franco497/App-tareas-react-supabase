-- ============================================================
-- App Tareas - Sistema de Gestión y Recordatorios
-- Schema de base de datos (solo estructura, sin datos)
-- ============================================================
-- NOTAS:
-- - No hay FOREIGN KEYS declaradas en esta base.
-- - `scheduled_notifications` usa TIMESTAMP WITHOUT TIME ZONE
--   (coherente con el manejo manual de UTC-3 en el cron).
-- - `magic_links` es solo auditoría: la validación real del
--   token se hace por firma JWT, no por consulta a la DB.
-- ============================================================

-- ============================================================
-- 1. TABLA: tasks
-- ============================================================
CREATE TABLE IF NOT EXISTS tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  name VARCHAR NOT NULL,
  done BOOLEAN DEFAULT FALSE,
  "userId" UUID NOT NULL,
  deleted BOOLEAN DEFAULT FALSE
);

-- ============================================================
-- 2. TABLA: scheduled_notifications
-- ============================================================
CREATE TABLE IF NOT EXISTS scheduled_notifications (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  task_id TEXT NOT NULL,
  task_name TEXT NOT NULL,
  user_email TEXT NOT NULL,
  scheduled_for TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  sent_at TIMESTAMP WITHOUT TIME ZONE
);

-- ============================================================
-- 3. TABLA: magic_links
-- ============================================================
CREATE TABLE IF NOT EXISTS magic_links (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  email TEXT NOT NULL,
  token TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  is_used BOOLEAN DEFAULT FALSE,
  ip_address TEXT,
  user_agent TEXT
);

-- ============================================================
-- 4. ÍNDICES
-- ============================================================

-- tasks
CREATE INDEX IF NOT EXISTS idx_tasks_user_id
  ON tasks("userId");

-- scheduled_notifications
CREATE INDEX IF NOT EXISTS idx_scheduled_notifications_status
  ON scheduled_notifications(status);

CREATE INDEX IF NOT EXISTS idx_scheduled_notifications_scheduled_for
  ON scheduled_notifications(scheduled_for);

-- magic_links
CREATE INDEX IF NOT EXISTS idx_magic_links_token
  ON magic_links(token);

CREATE INDEX IF NOT EXISTS idx_magic_links_email
  ON magic_links(email);

CREATE INDEX IF NOT EXISTS idx_magic_links_created_at
  ON magic_links(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_magic_links_valid
  ON magic_links(token, is_used, expires_at);

-- ============================================================
-- 5. FUNCIÓN + TRIGGER: reactivar tarea programada
-- ============================================================
CREATE OR REPLACE FUNCTION reactivate_scheduled_task()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status = 'pending' AND OLD.status IN ('sent', 'failed') THEN
    NEW.sent_at = NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trigger_reactivate_scheduled_task
  ON scheduled_notifications;

CREATE TRIGGER trigger_reactivate_scheduled_task
BEFORE UPDATE ON scheduled_notifications
FOR EACH ROW
EXECUTE FUNCTION reactivate_scheduled_task();

-- ============================================================
-- 6. ROW LEVEL SECURITY (RLS)
-- ============================================================

ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE scheduled_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE magic_links ENABLE ROW LEVEL SECURITY;

-- ---------- Políticas: tasks ----------
DROP POLICY IF EXISTS "Usuarios pueden ver sus propias tareas" ON tasks;
CREATE POLICY "Usuarios pueden ver sus propias tareas"
  ON tasks FOR SELECT
  USING (auth.uid() = "userId");

DROP POLICY IF EXISTS "Usuarios pueden crear sus propias tareas" ON tasks;
CREATE POLICY "Usuarios pueden crear sus propias tareas"
  ON tasks FOR INSERT
  WITH CHECK (auth.uid() = "userId");

DROP POLICY IF EXISTS "Usuarios pueden actualizar sus propias tareas" ON tasks;
CREATE POLICY "Usuarios pueden actualizar sus propias tareas"
  ON tasks FOR UPDATE
  USING (auth.uid() = "userId")
  WITH CHECK (auth.uid() = "userId");

DROP POLICY IF EXISTS "Usuarios pueden eliminar sus propias tareas" ON tasks;
CREATE POLICY "Usuarios pueden eliminar sus propias tareas"
  ON tasks FOR DELETE
  USING (auth.uid() = "userId");

